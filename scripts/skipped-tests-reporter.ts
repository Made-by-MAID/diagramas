import { writeFileSync } from "node:fs";
import { relative } from "node:path";
import type { Reporter, TestModule } from "vitest/node";

const REPORT_PATH = "docs/skipped-tests.md";
const FULL_RUN_MARKER = "test/e2e/real-binaries.spec.ts";

// Skipped tests must never look like success, so every run rewrites this report and prints it.
export default class SkippedTestsReporter implements Reporter {
  onTestRunEnd(testModules: readonly TestModule[]): void {
    const skipped: string[] = [];
    for (const testModule of testModules) {
      const file = relative(process.cwd(), testModule.moduleId);
      for (const test of testModule.children.allTests()) {
        const result = test.result();
        if (result.state === "skipped") {
          skipped.push(`- \`${file}\` — ${test.fullName}: ${result.note ?? "no reason given"}`);
        }
      }
    }
    const fullRun = testModules.some((testModule) => testModule.moduleId.endsWith(FULL_RUN_MARKER));
    const body =
      skipped.length === 0 ? "No test was skipped in the last run.\n" : `${skipped.join("\n")}\n`;
    if (fullRun) {
      writeFileSync(
        REPORT_PATH,
        `# Skipped tests\n\nGenerated by \`scripts/skipped-tests-reporter.ts\` on every full run of the suite.\nA test skipped here does not count as a success: what it covers was not verified.\n\n${body}`,
      );
    }
    if (skipped.length > 0) {
      process.stdout.write(`\nSKIPPED TESTS (${skipped.length}):\n${skipped.join("\n")}\n`);
    }
  }
}
